interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, values?: Record<string, string | number>) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

function storedLanguage(): Language {
  return window.localStorage.getItem("gamevault-language") === "lt" ? "lt" : "en";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setCurrentLanguage] = useState<Language>(storedLanguage);

  const setLanguage = useCallback((nextLanguage: Language) => {
    window.localStorage.setItem("gamevault-language", nextLanguage);
    setCurrentLanguage(nextLanguage);
  }, []);

  const t = useCallback((key: string, values?: Record<string, string | number>) => {
    const message = translations[key]?.[language] ?? key;
    return message.replace(/\{(\w+)\}/g, (_, name: string) => String(values?.[name] ?? `{${name}}`));
  }, [language]);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

// The provider and its context hook intentionally share the localization module.
// eslint-disable-next-line react-refresh/only-export-components
export function useTranslation(): LanguageContextValue {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useTranslation must be used within LanguageProvider.");
  return context;
}
